#!/usr/bin/env python3
"""Configure this App's Python package index without changing its chat server."""
import argparse
import json
import os
from pathlib import Path
import sys
import tempfile
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
MANAGED = '# Generated by XGO Duck Python setup.\n'
INDEXES = {'cn': 'https://pypi.tuna.tsinghua.edu.cn/simple/',
           'global': 'https://pypi.org/simple/'}


def validate_index(url):
    parsed = urlsplit(url)
    if (len(url) > 2048 or any(c.isspace() for c in url) or parsed.scheme != 'https'
            or not parsed.hostname or parsed.username is not None or parsed.password is not None
            or parsed.query or parsed.fragment):
        raise ValueError('Python index must be an HTTPS URL without credentials, query or fragment.')
    return url.rstrip('/') + '/'


def configure(root, region, index_url=None):
    path = root / 'uv.toml'
    if path.is_symlink():
        raise ValueError('uv.toml is a symlink; configure that file manually.')
    old = path.read_text() if path.exists() else ''
    if old and index_url is None and (not old.startswith(MANAGED) or '# selection: custom\n' in old):
        print('Keeping the existing custom uv.toml; no package or chat server setting changed.')
        return None
    url = validate_index(index_url or INDEXES.get(region, INDEXES['global']))
    content = (MANAGED + '# selection: ' + ('custom' if index_url else 'auto') + '\n'
               '[[index]]\nname = "xgoduck-packages"\nurl = ' + json.dumps(url) + '\ndefault = true\n')
    if content != old:
        if old and not old.startswith(MANAGED):
            backup = root / '.uv.toml.before-xgoduck'
            if not backup.exists():
                backup.write_text(old)
                backup.chmod(0o600)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=root, prefix='.uv-', delete=False) as target:
                temporary = Path(target.name)
                target.write(content)
                target.flush()
                os.fsync(target.fileno())
            temporary.chmod(0o644)
            temporary.replace(path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    print('Python dependency index:', url)
    print('This local uv.toml is excluded from the distributed App ZIP; chat settings are unchanged.')
    return url


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--index-url', help='Explicit HTTPS package mirror override; kept on later setup runs')
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT / 'python'))
    from voice_config import VoiceConfig
    config = VoiceConfig(ROOT / 'data/voice_config.json')
    try:
        if config.path.exists():
            VoiceConfig.validate(json.loads(config.path.read_text()))
        configure(ROOT, config.get()['cloud_region'], args.index_url)
    except (OSError, ValueError, TypeError) as error:
        parser.exit(2, f'Cannot configure Python downloads: {error}\n')


if __name__ == '__main__':
    main()
